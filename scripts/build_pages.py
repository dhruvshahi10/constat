def esc(t) -> str:
    return html.escape(str(t), quote=False)


def shell(title: str, active: str, head: str, body: str, description: str) -> str:
    nav = "".join(f'<a href="{h}"{" class=\"on\"" if h == active else ""}>{esc(l)}</a>'
                  for h, l in NAV)
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(title)}</title>
<meta name="description" content="{html.escape(description, quote=True)}">
<style>{brand.stylesheet(CSS)}</style></head><body>
<div class="pg">
<div class="pg-top"><nav>{nav}</nav>
<a href="mailto:{esc(CONTACT)}?subject=Constat">Get in touch</a></div>
{head}
{body}
<div class="pg-foot">
Constat &middot; page generated {date.today().isoformat()} &middot;
<a href="/">back to the product</a><br>
All customer data shown anywhere on this site is synthetic.
</div>
</div></body></html>"""


def head(h1: str, lede: str) -> str:
    return f'<div class="pg-head"><h1>{esc(h1)}</h1><p>{lede}</p></div>'


# --- /trust/ ------------------------------------------------------------------
def build_trust() -> tuple[str, dict]:
    r = trustpage.generate("constat", ROOT / "data" / "evidence",
                           display_name="Constat", today=date.today())
    by_domain: dict[str, list] = {}
    for a in r.answers:
        by_domain.setdefault(a.domain, []).append(a)

    blocks = []
    for domain, items in by_domain.items():
        blocks.append(f'<div class="dom">{esc(domain)}</div>')
        for a in items:
            if a.published:
                prov = "<br>".join(
                    f"{esc(c['source_id'])} &middot; v{esc(c['version'])} &middot; {esc(c['location'])}"
                    for c in a.citations)
                blocks.append(f'<div class="qa"><div class="q">{esc(a.question)}</div>'
                              f'<div class="a">{esc(a.answer)}</div>'
                              f'<div class="prov">{prov}</div></div>')
            else:
                blocks.append(f'<div class="qa open"><div class="q">{esc(a.question)}</div>'
                              f'<div class="req">Not published &mdash; our evidence does not '
                              f'support a self-serve answer. Ask us through security review.'
                              f'</div></div>')

    pct = round(r.deflection_rate * 100)
    body = f"""
<div class="stats">
<div class="stat on"><b>{pct}%</b><span>answered self-serve</span></div>
<div class="stat"><b>{len(r.shown)}</b><span>with citations</span></div>
<div class="stat"><b>{len(r.open_items)}</b><span>open &mdash; ask us</span></div>
<div class="stat"><b>{len(r.answers)}</b><span>standard questions</span></div>
</div>
<div class="note"><b>How to read this page.</b> An answer appears only when every claim in it is
supported by an approved, in-force document, and it names that document, its version and the
paragraph. We hold no certifications, so every certification question below is refused &mdash;
including ISO&nbsp;42001, where the only document on file is a roadmap, and a roadmap is not a
certificate.</div>
{''.join(blocks)}
"""
    page = shell("Trust centre — Constat", "/trust/",
                 head("Our own security answers, produced by our own engine.",
                      "Every answer below was generated by the system this page describes, from "
                      "our own evidence corpus, under the same gates that run for a customer. "
                      "Nothing here was written by hand. Questions our evidence cannot support "
                      "are listed as open rather than answered with something plausible &mdash; "
                      "which is the entire argument, applied to ourselves."),
                 body, "Constat's own security answers, generated by Constat.")
    return page, r.to_dict()


