    pages = {"trust": trust_html, "how-it-works": build_how(), "pricing": build_pricing()}
    for name, markup in pages.items():
        target = SITE / name / "index.html"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(markup, encoding="utf-8")
        print(f"  wrote site/{name}/index.html ({target.stat().st_size // 1024}KB)")
    print(f"trust centre: {trust_data['published']}/{trust_data['questions']} answered "
          f"({trust_data['deflection_rate']:.1%} deflection)")
    return 0


